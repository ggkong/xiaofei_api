package conversationarchive

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/Wei-Shaw/sub2api/internal/archivewire"
	"golang.org/x/crypto/ssh"
)

type LocalDevice struct {
	ID               string     `json:"id"`
	Name             string     `json:"name"`
	PublicKey        string     `json:"public_key"`
	OwnerID          int64      `json:"owner_id"`
	Enabled          bool       `json:"enabled"`
	OffloadEnabled   bool       `json:"offload_enabled"`
	KeepDays         int        `json:"keep_days"`
	ConfirmedRecords int64      `json:"confirmed_records"`
	LastSeenAt       *time.Time `json:"last_seen_at"`
	CreatedAt        time.Time  `json:"created_at"`
}
type LocalReference struct {
	DeviceID      string    `json:"device_id"`
	Digest        string    `json:"digest"`
	ArchivedAt    time.Time `json:"archived_at"`
	OriginalBytes int64     `json:"original_bytes"`
}

const deviceColumns = `d.id,d.name,d.public_key,d.owner_id,d.enabled,d.offload_enabled,d.keep_days,d.confirmed_records,d.last_seen_at,d.created_at`

func scanDevice(row scanner) (LocalDevice, error) {
	var d LocalDevice
	err := row.Scan(&d.ID, &d.Name, &d.PublicKey, &d.OwnerID, &d.Enabled, &d.OffloadEnabled, &d.KeepDays, &d.ConfirmedRecords, &d.LastSeenAt, &d.CreatedAt)
	return d, err
}
func (s *Store) LocalDevices(ctx context.Context) ([]LocalDevice, error) {
	if s == nil || s.db == nil {
		return nil, errors.New("archive unavailable")
	}
	rows, err := s.db.QueryContext(ctx, `SELECT `+deviceColumns+` FROM conversation_archive_devices d ORDER BY d.created_at DESC`)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	devices := []LocalDevice{}
	for rows.Next() {
		d, err := scanDevice(rows)
		if err != nil {
			return nil, err
		}
		devices = append(devices, d)
	}
	return devices, rows.Err()
}
func (s *Store) PairLocalDevice(ctx context.Context, owner int64, name, key string) (LocalDevice, error) {
	if s == nil || s.db == nil {
		return LocalDevice{}, errors.New("archive unavailable")
	}
	name = strings.TrimSpace(name)
	if owner < 1 || name == "" || !utf8.ValidString(name) || len([]rune(name)) > 100 || strings.ContainsRune(name, 0) || len(key) > 1024 {
		return LocalDevice{}, errors.New("invalid device name or public key")
	}
	public, _, options, rest, err := ssh.ParseAuthorizedKey([]byte(key))
	if err != nil || len(options) > 0 || len(strings.TrimSpace(string(rest))) > 0 || public.Type() != ssh.KeyAlgoED25519 {
		return LocalDevice{}, errors.New("use the ed25519 public key generated by the Windows tool")
	}
	hash := sha256.Sum256(public.Marshal())
	id := hex.EncodeToString(hash[:])
	canonical := strings.TrimSpace(string(ssh.MarshalAuthorizedKey(public)))
	return scanDevice(s.db.QueryRowContext(ctx, `INSERT INTO conversation_archive_devices AS d(id,name,public_key,owner_id) VALUES($1,$2,$3,$4)
 ON CONFLICT(id) DO UPDATE SET name=EXCLUDED.name,owner_id=EXCLUDED.owner_id,enabled=TRUE,offload_enabled=FALSE RETURNING `+deviceColumns, id, name, canonical, owner))
}
func (s *Store) UpdateLocalDevice(ctx context.Context, id string, enabled, offload bool, days int) (LocalDevice, error) {
	if s == nil || s.db == nil {
		return LocalDevice{}, errors.New("archive unavailable")
	}
	if !archivewire.ValidHash(id) || days < 1 || days > 3650 {
		return LocalDevice{}, errors.New("keep 1–3650 recent days on the server")
	}
	return scanDevice(s.db.QueryRowContext(ctx, `UPDATE conversation_archive_devices AS d SET enabled=$2,offload_enabled=$3,keep_days=$4 WHERE id=$1 AND (NOT $3 OR confirmed_records>0) RETURNING `+deviceColumns, id, enabled, offload, days))
}
func (s *Store) AuthorizedLocalDevice(ctx context.Context, id string) (LocalDevice, error) {
	if s == nil || s.db == nil || !archivewire.ValidHash(id) {
		return LocalDevice{}, errors.New("archive device unavailable")
	}
	return scanDevice(s.db.QueryRowContext(ctx, `SELECT `+deviceColumns+` FROM conversation_archive_devices d JOIN users u ON u.id=d.owner_id WHERE d.id=$1 AND d.enabled AND u.role='admin' AND u.status='active' AND u.deleted_at IS NULL`, id))
}
func (s *Store) AuthorizedLocalKeys(ctx context.Context) ([]LocalDevice, error) {
	if s == nil || s.db == nil {
		return nil, errors.New("archive unavailable")
	}
	rows, err := s.db.QueryContext(ctx, `SELECT `+deviceColumns+` FROM conversation_archive_devices d JOIN users u ON u.id=d.owner_id WHERE d.enabled AND u.role='admin' AND u.status='active' AND u.deleted_at IS NULL ORDER BY d.id`)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	devices := []LocalDevice{}
	for rows.Next() {
		d, err := scanDevice(rows)
		if err != nil {
			return nil, err
		}
		devices = append(devices, d)
	}
	return devices, rows.Err()
}

